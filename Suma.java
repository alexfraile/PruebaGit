/**
 * Clase que realiza sumas simples.
 * @author Deivis
 * @version 1.0
 */
public class Suma {
    /**
     * Suma dos números enteros.
     * @param a Primer número.
     * @param b Segundo número.
     * @return La suma de a y b.
     */
    public int sumar(int a, int b) {
        return a + b;
    }
}
